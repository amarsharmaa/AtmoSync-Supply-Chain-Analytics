
SELECT
    CONTAINER_ID,
    COUNT(*) AS TOTAL_READINGS,
    ROUND(AVG(TEMPERATURE_C), 2) AS AVG_TEMPERATURE,
    ROUND(AVG(HUMIDITY_PERCENT), 2) AS AVG_HUMIDITY,

    COUNT_IF(SPOILAGE_RISK = 'HIGH') AS HIGH_RISK_READINGS,

    CASE
        WHEN COUNT_IF(SPOILAGE_RISK = 'HIGH') > 0
        THEN 'HIGH'
        WHEN COUNT_IF(SPOILAGE_RISK = 'MEDIUM') > 0
        THEN 'MEDIUM'
        ELSE 'LOW'
    END AS OVERALL_RISK

FROM {{ ref('container_spoilage_risk') }}

GROUP BY CONTAINER_ID
