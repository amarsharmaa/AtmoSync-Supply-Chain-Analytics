
SELECT
    r.CONTAINER_ID,
    r.ROUTE_ID,
    r.EXPECTED_TEMPERATURE_C,
    r.TRAVEL_TIME_HOURS,
    r.TRANSPORT_COST_INR,
    s.OVERALL_RISK AS CURRENT_CONTAINER_RISK,

    CASE
        WHEN r.EXPECTED_TEMPERATURE_C > 12
        THEN 'HIGH'
        WHEN r.EXPECTED_TEMPERATURE_C > 8
        THEN 'MEDIUM'
        ELSE 'LOW'
    END AS ROUTE_TEMPERATURE_RISK

FROM ATMOSYNC_DB.RAW.ROUTE_OPTIONS r

LEFT JOIN {{ ref('container_risk_summary') }} s
    ON r.CONTAINER_ID = s.CONTAINER_ID
